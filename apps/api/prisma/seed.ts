  const passwordHash = await hash('12356', 1)

  const user = await prisma.user.create({
    data: {
      name: 'John Doe',
      email: 'john@acme.com',
      avatarUrl: 'https://github.com/mercurio236.png',
      passwordHash,
    },
  })
